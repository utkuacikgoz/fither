#!/usr/bin/env node
// FITHER voice audio: every coaching cue in data/movements.json, spoken
// once by the app's one coach voice, bundled with the app.
//
// Offline-first is a hard rule (CLAUDE.md), so audio is generated HERE,
// committed under app/assets/voice/, and required statically through the
// manifest this script writes — the app never fetches speech at runtime.
// Like the movement figures and the brand set: regenerate, never retouch.
//
// Provider: ElevenLabs (decided, docs/build-system.md §9). The voice is
// the owner's one-time taste choice and the key is the owner's, so the
// script takes both from the environment and does nothing else without
// them:
//
//   ELEVENLABS_API_KEY=... ELEVENLABS_VOICE_ID=... \
//     node scripts/generate-voice-audio.mjs
//
// Flags:
//   --manifest-only  rewrite the manifest from whatever mp3s exist (no
//                    network; the app builds with an empty manifest)
//   --dry-run        list what would be generated and the character cost
//   --force          regenerate files that already exist
//
// Files are keyed by a hash of the cue TEXT, so identical cues across
// movements share one file, an edited cue regenerates exactly itself,
// and an untouched cue is never billed twice.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const LIBRARY = path.join(root, "data", "movements.json");
const OUT_DIR = path.join(root, "app", "assets", "voice");
const MANIFEST = path.join(root, "app", "src", "session", "voice-manifest.ts");
const MODEL = "eleven_turbo_v2_5";
const OUTPUT_FORMAT = "mp3_22050_32"; // small, plenty for short spoken cues

const args = new Set(process.argv.slice(2));
const manifestOnly = args.has("--manifest-only");
const dryRun = args.has("--dry-run");
const force = args.has("--force");

const keyOf = (text) => createHash("sha1").update(text).digest("hex").slice(0, 12);

const movements = JSON.parse(readFileSync(LIBRARY, "utf8")).movements;
const cues = [...new Set(movements.flatMap((m) => m.cues))].sort();

mkdirSync(OUT_DIR, { recursive: true });

function writeManifest() {
  const present = cues.filter((cue) => existsSync(path.join(OUT_DIR, `${keyOf(cue)}.mp3`)));
  const entries = present
    .map((cue) => `  ${JSON.stringify(cue)}: require("../../assets/voice/${keyOf(cue)}.mp3"),`)
    .join("\n");
  const body = `// GENERATED by scripts/generate-voice-audio.mjs — do not edit.
// One spoken file per unique coaching cue, keyed by the cue's exact text
// so the player looks up the line it is already showing. Empty until the
// owner runs the generator with the chosen voice; the app builds either
// way and voice simply has nothing to say.
import type { AudioSource } from "expo-audio";

export const voiceCues: Record<string, AudioSource> = {
${entries}
};

/** The spoken file for a cue, or null when none was generated. */
export function voiceCue(cue: string): AudioSource | null {
  return voiceCues[cue] ?? null;
}

/** Whether ANY spoken cue is bundled — the Settings card's existence. */
export function hasVoiceAudio(): boolean {
  return Object.keys(voiceCues).length > 0;
}
`;
  writeFileSync(MANIFEST, body);
  // Orphans: files no cue references any more (a cue was edited away).
  const wanted = new Set(cues.map((c) => `${keyOf(c)}.mp3`));
  const orphans = readdirSync(OUT_DIR).filter((f) => f.endsWith(".mp3") && !wanted.has(f));
  for (const f of orphans) unlinkSync(path.join(OUT_DIR, f));
  return { present: present.length, orphans: orphans.length };
}

if (manifestOnly) {
  const { present, orphans } = writeManifest();
  console.log(`manifest: ${present}/${cues.length} cues have audio; ${orphans} orphan file(s) removed`);
  process.exit(0);
}

const todo = cues.filter((cue) => force || !existsSync(path.join(OUT_DIR, `${keyOf(cue)}.mp3`)));
const chars = todo.reduce((n, c) => n + c.length, 0);
console.log(`${cues.length} unique cues across ${movements.length} movements; ${todo.length} to generate (${chars} characters)`);
if (dryRun) process.exit(0);

const apiKey = process.env.ELEVENLABS_API_KEY;
const voiceId = process.env.ELEVENLABS_VOICE_ID;
if (!apiKey || !voiceId) {
  console.error("Set ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID (the owner's key and chosen voice).");
  process.exit(1);
}

let done = 0;
for (const cue of todo) {
  const res = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${voiceId}?output_format=${OUTPUT_FORMAT}`,
    {
      method: "POST",
      headers: { "xi-api-key": apiKey, "content-type": "application/json", accept: "audio/mpeg" },
      body: JSON.stringify({ text: cue, model_id: MODEL }),
    },
  );
  if (!res.ok) {
    console.error(`failed (${res.status}) on: ${cue}\n${await res.text()}`);
    process.exit(1);
  }
  writeFileSync(path.join(OUT_DIR, `${keyOf(cue)}.mp3`), Buffer.from(await res.arrayBuffer()));
  done += 1;
  process.stdout.write(`\r${done}/${todo.length}`);
}
console.log();
const { present, orphans } = writeManifest();
console.log(`generated ${done}; manifest: ${present}/${cues.length}; ${orphans} orphan file(s) removed`);
